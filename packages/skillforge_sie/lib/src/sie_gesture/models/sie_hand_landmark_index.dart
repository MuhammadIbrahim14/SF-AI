  /// Middle fingertip.
  static const int middleTip = 12;

  /// Middle MCP.
  static const int middleMcp = 9;

  /// Ring fingertip.
  static const int ringTip = 16;

  /// Pinky tip.
  static const int pinkyTip = 20;

  /// Pinky MCP.
  static const int pinkyMcp = 17;
}
